// Package ambe decodes AMBE+2 half-rate ("3600x2450") voice as carried by
// P25 Phase 2 TDMA: 72-bit codewords, 20 ms each, 2450 bps of speech
// parameters plus 1150 bps of FEC, synthesised to 160 samples of 8 kHz PCM.
//
// The pipeline per codeword is:
//
//	p25p2.go   72 on-air bits → c0..c3 → Golay + PRNG de-scramble → 49-bit Frame
//	params.go  Frame → pitch, voicing, spectral magnitudes (differential vs last frame)
//	synth.go   parameters → overlap-added harmonic/noise synthesis → PCM
//	decoder.go per-stream state and mbelib's repeat/mute error handling
//
// It is pure Go so receivers cross-compile for the Pi without cgo.
//
// # Provenance
//
// This is a port of open-source decoders, not a clean-room implementation:
//
//   - mbelib (github.com/szechyjs/mbelib, ISC licence, © 2010 mbelib Author):
//     ambe3600x2450.c parameter dequantisation and quantiser tables,
//     mbelib.c spectral enhancement, synthesis and parameter handling,
//     ecc.c Golay layout.
//   - OP25 (github.com/boatbod/op25, GPLv3, © Max H. Parke KA1RBI):
//     p25p2_vf.cc vocoder-codeword de-interleave, the u0-seeded PRNG mask
//     over c1, the b0..b8 bit packing, and rs.cc's Golay conventions.
//
// Behaviour matches mbelib frame for frame (see the golden-vector tests in
// testdata/, generated by linking mbelib and OP25 into a C harness) with
// three deliberate differences: unvoiced noise comes from a seeded xorshift
// generator instead of libc rand(); synthesis phases are kept wrapped in
// float64 rather than growing unbounded in float32; and c0's Golay(24,12)
// parity bit is checked, so four errors in c0 repeat the frame instead of
// being decoded as a wrong codeword.
//
// Tone frames (b0 126/127) are muted, as in mbelib; OP25 synthesises them.
