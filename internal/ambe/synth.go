package ambe

import "math"

// MBE speech synthesis, ported from mbelib's mbe_spectralAmpEnhance and
// mbe_synthesizeSpeechf. Each 160-sample frame is the overlap-add of the
// previous frame's harmonics fading out and the current frame's fading in.
// Voiced harmonics are sinusoids whose phase is carried across frames;
// unvoiced ones are a small cluster of random-phase sinusoids around the
// harmonic (mbelib's "multisine" noise, uvquality = 3) plus, above 2.7 kHz,
// a random offset.
//
// mbelib evaluates cosf() for every sample. Every cosine here has a phase
// that is linear in n, so it is generated by a two-term recurrence instead
// (see osc), with all of a band's oscillators stepped in one loop so their
// dependency chains overlap. That is what makes four streams cheap on a Pi;
// over 160 samples the recurrence drifts by ~1e-13, far below one LSB.

const (
	frameSamples = 160

	// uvQuality is the number of sinusoids per unvoiced band (mbelib's
	// uvquality, DSD's default). synthesize unrolls it: it must stay 3.
	uvQuality = 3
	uvStep    = 1.0 / uvQuality
	uvOffset  = uvStep * (uvQuality - 1) / 2

	uvSine = 1.3591409 * math.E
	uvRand = 2.0
	// pcmGain is mbelib's fixed float→int16 gain.
	pcmGain = 7
	pcmClip = 32760
)

var (
	// uvThreshold is the harmonic frequency above which unvoiced bands get
	// extra random energy (2.7 kHz). It decides whether the noise generator
	// is consulted, so it is compared in float32 exactly as in mbelib to keep
	// the generator's sequence aligned.
	uvThreshold = float32(2700 * math.Pi / 4000)
	// uvQFactor is mbelib's log(uvquality)/uvquality normalisation.
	uvQFactor = math.Log(uvQuality) / uvQuality
)

// noise is the generator behind mbelib's rand() calls. It is xorshift32
// rather than libc rand() so output is reproducible on every platform; the
// golden-vector harness links mbelib against the same generator.
type noise struct{ s uint32 }

const noiseSeed = 0x9E3779B9

// next returns a value in [0, 1], computed in float32 as mbe_rand() does.
func (r *noise) next() float64 {
	r.s ^= r.s << 13
	r.s ^= r.s >> 17
	r.s ^= r.s << 5
	return float64(float32(r.s>>1) / float32(math.MaxInt32))
}

// sum3 is three successive draws summed, as one multisine sample uses.
func (r *noise) sum3() float64 {
	a := r.next()
	b := r.next()
	return a + b + r.next()
}

// phase returns a value in [-π, π] (mbe_rand_phase).
func (r *noise) phase() float64 {
	const pi = float32(math.Pi)
	// The inner conversion stops the compiler fusing this into an FMA,
	// which mbelib's float32 arithmetic doesn't do.
	return float64(float32(float32(r.next())*(pi*2)) - pi)
}

// osc generates cos(φ + ω·n) for n = 0, 1, 2, … by the Chebyshev
// recurrence c[n+1] = 2cos(ω)·c[n] − c[n−1]: one fused multiply-subtract per
// sample, three registers of state.
type osc struct{ c0, c1, k float64 }

func newOsc(phase, step float64) osc {
	return osc{c0: math.Cos(phase), c1: math.Cos(phase + step), k: 2 * math.Cos(step)}
}

func (o *osc) next() float64 {
	v := o.c0
	o.c0, o.c1 = o.c1, o.k*o.c1-o.c0
	return v
}

// enhance is mbe_spectralAmpEnhance: it sharpens formants by weighting each
// magnitude against the frame's spectral tilt, then restores the total
// energy.
func enhance(p *mbeParams) {
	var rm0, rm1 float64
	for l := 1; l <= p.L; l++ {
		m2 := p.ml[l] * p.ml[l]
		rm0 += m2
		rm1 += m2 * math.Cos(p.w0*float64(l))
	}
	r2m0, r2m1 := rm0*rm0, rm1*rm1
	for l := 1; l <= p.L; l++ {
		if p.ml[l] == 0 || 8*l <= p.L {
			continue
		}
		w := math.Sqrt(p.ml[l]) * math.Pow(
			0.96*math.Pi*((r2m0+r2m1)-2*rm0*rm1*math.Cos(p.w0*float64(l)))/(p.w0*rm0*(r2m0-r2m1)),
			0.25)
		switch {
		case w > 1.2:
			p.ml[l] *= 1.2
		case w < 0.5:
			p.ml[l] *= 0.5
		default:
			p.ml[l] *= w
		}
	}
	var sum float64
	for l := 1; l <= p.L; l++ {
		sum += p.ml[l] * p.ml[l]
	}
	gain := 1.0
	if sum != 0 {
		gain = math.Sqrt(rm0 / sum)
	}
	for l := 1; l <= p.L; l++ {
		p.ml[l] *= gain
	}
}

// wrapPhase reduces x to [-π, π). mbelib lets the accumulator grow without
// bound in float32, which quietly loses phase precision a few seconds into
// a call; wrapping keeps it exact indefinitely.
func wrapPhase(x float64) float64 {
	return x - 2*math.Pi*math.Floor((x+math.Pi)/(2*math.Pi))
}

// synthesize renders one frame into out (unscaled float samples) from cur,
// overlapping prev. Like mbelib it pads whichever of the two has fewer
// harmonics with silent voiced ones, writing into both.
func synthesize(out *[frameSamples]float64, cur, prev *mbeParams, rng *noise) {
	const N = frameSamples
	*out = [N]float64{}

	numUV := 0
	for l := 1; l <= cur.L; l++ {
		if !cur.voiced[l] {
			numUV++
		}
	}
	cw0, pw0 := cur.w0, prev.w0
	// mbelib's w0·l products are float32; these decide noise use below.
	cw0f, pw0f := float32(cur.w0), float32(prev.w0)

	maxl := cur.L
	if cur.L > prev.L {
		for l := prev.L + 1; l <= maxl; l++ {
			prev.ml[l] = 0
			prev.voiced[l] = true
		}
	} else {
		maxl = prev.L
		for l := cur.L + 1; l <= maxl; l++ {
			cur.ml[l] = 0
			cur.voiced[l] = true
		}
	}

	// Phase advance (eqs. 139-140). Upper harmonics get a random dither
	// proportional to how unvoiced the frame is.
	for l := 1; l <= maxL; l++ {
		cur.psi[l] = wrapPhase(prev.psi[l] + (pw0+cw0)*float64(l*N)/2)
		if l <= cur.L/4 {
			cur.phi[l] = cur.psi[l]
		} else {
			cur.phi[l] = cur.psi[l] + float64(numUV)*rng.phase()/float64(cur.L)
		}
	}

	var rphase, rphase2 [uvQuality]float64
	for l := 1; l <= maxl; l++ {
		fl := float64(l)
		cw0l, pw0l := cw0*fl, pw0*fl
		// Unvoiced bands above 2.7 kHz get a random offset added to each
		// multisine term.
		cw0lf, pw0lf := float32(cw0f*float32(l)), float32(pw0f*float32(l))
		cNoise, pNoise := cw0lf > uvThreshold, pw0lf > uvThreshold
		cAmp := float64(cw0lf-uvThreshold) * uvRand
		pAmp := float64(pw0lf-uvThreshold) * uvRand
		cGain := uvSine * cur.ml[l] * uvQFactor
		pGain := uvSine * prev.ml[l] * uvQFactor

		switch {
		case !cur.voiced[l] && prev.voiced[l]:
			// Voiced → unvoiced: fade out the old sinusoid, fade in noise.
			for i := range rphase {
				rphase[i] = rng.phase()
			}
			s := newOsc(prev.phi[l], pw0l)
			m0, m1, m2 := multisine(cw0, fl, &rphase)
			pm := prev.ml[l]
			for n := range N {
				u := m0.next() + m1.next() + m2.next()
				if cNoise {
					u += cAmp * rng.sum3()
				}
				out[n] += winPrev[n]*pm*s.next() + u*cGain*winCur[n]
			}

		case cur.voiced[l] && !prev.voiced[l]:
			// Unvoiced → voiced: fade out noise, fade in the new sinusoid.
			for i := range rphase {
				rphase[i] = rng.phase()
			}
			s := newOsc(cur.phi[l]-cw0l*N, cw0l)
			m0, m1, m2 := multisine(pw0, fl, &rphase)
			cm := cur.ml[l]
			for n := range N {
				u := m0.next() + m1.next() + m2.next()
				if pNoise {
					u += pAmp * rng.sum3()
				}
				out[n] += winCur[n]*cm*s.next() + u*pGain*winPrev[n]
			}

		case cur.voiced[l] || prev.voiced[l]:
			// Voiced in both: cross-fade the two sinusoids (eq. 133).
			s1 := newOsc(prev.phi[l], pw0l)
			s2 := newOsc(cur.phi[l]-cw0l*N, cw0l)
			pm, cm := prev.ml[l], cur.ml[l]
			for n := range N {
				out[n] += winPrev[n]*pm*s1.next() + winCur[n]*cm*s2.next()
			}

		default:
			// Unvoiced in both: cross-fade two independent noise clusters.
			for i := range rphase {
				rphase[i] = rng.phase()
			}
			for i := range rphase2 {
				rphase2[i] = rng.phase()
			}
			p0, p1, p2 := multisine(pw0, fl, &rphase)
			c0, c1, c2 := multisine(cw0, fl, &rphase2)
			for n := range N {
				up := p0.next() + p1.next() + p2.next()
				if pNoise {
					up += pAmp * rng.sum3()
				}
				uc := c0.next() + c1.next() + c2.next()
				if cNoise {
					uc += cAmp * rng.sum3()
				}
				out[n] += up*pGain*winPrev[n] + uc*cGain*winCur[n]
			}
		}
	}
}

// multisine returns the oscillators of an unvoiced band: uvQuality
// sinusoids spread across harmonic l's band, cos(rphase[i] + w0·(l + i·step
// − offset)·n).
func multisine(w0, l float64, rphase *[uvQuality]float64) (a, b, c osc) {
	step := func(i int) float64 { return w0 * (l + float64(i)*uvStep - uvOffset) }
	return newOsc(rphase[0], step(0)), newOsc(rphase[1], step(1)), newOsc(rphase[2], step(2))
}

// winCur and winPrev are synthWindow's two halves as float64: the fade-in
// applied to the current frame and the fade-out applied to the previous.
var winCur, winPrev [frameSamples]float64

func init() {
	for n := range frameSamples {
		winCur[n] = float64(synthWindow[n])
		winPrev[n] = float64(synthWindow[n+frameSamples])
	}
}

// toPCM is mbe_floattoshort: fixed gain, clip, truncate.
func toPCM(in *[frameSamples]float64) (pcm [frameSamples]int16) {
	for i, v := range in {
		v *= pcmGain
		if v != v { // NaN from a degenerate frame; int16(NaN) is undefined
			v = 0
		}
		pcm[i] = int16(max(-pcmClip, min(pcmClip, v)))
	}
	return pcm
}
